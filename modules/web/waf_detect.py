from core.base_module import BaseModule
from core.utils import print_status, Colors, normalize_url
from core import http


# (vendor, [header/cookie/body signatures]) - matched case-insensitively
WAF_SIGNATURES = [
    ("Cloudflare", ["cf-ray", "cloudflare", "__cfduid", "cf_clearance",
                    "attention required! | cloudflare", "cf-mitigated"]),
    ("Akamai", ["akamaighost", "x-akamai", "akamai"]),
    ("AWS WAF / CloudFront", ["x-amz-cf-id", "x-amzn-requestid", "awselb",
                              "cloudfront", "x-amz-apigw-id"]),
    ("Imperva Incapsula", ["x-iinfo", "incap_ses", "visid_incap", "incapsula",
                           "x-cdn", "_incapsula_"]),
    ("Sucuri CloudProxy", ["x-sucuri-id", "x-sucuri-cache", "sucuri/cloudproxy",
                           "access denied - sucuri website firewall"]),
    ("F5 BIG-IP ASM", ["x-waf-event", "the requested url was rejected",
                       "bigipserver", "x-cnection"]),
    ("Barracuda", ["barra_counter_session", "barracuda"]),
    ("ModSecurity", ["mod_security", "this error was generated by mod_security",
                     "modsecurity"]),
    ("Wordfence", ["generated by wordfence", "wordfence"]),
    ("Fortinet FortiWeb", ["fortiwafsid", "fortiweb", ".fgd_icon"]),
    ("Citrix NetScaler", ["ns_af", "citrix ns", "nsc_", "via: ns-cache"]),
    ("DDoS-Guard", ["ddos-guard"]),
    ("StackPath", ["stackpath"]),
    ("Fastly", ["x-served-by", "fastly", "fastly-debug", "x-fastly"]),
    ("Varnish", ["x-varnish", "via: varnish"]),
    ("Palo Alto", ["has been blocked in accordance with company policy"]),
    ("Wallarm", ["nginx-wallarm"]),
    ("Reblaze", ["rbzid", "reblaze"]),
    ("Edgecast", ["ecdf", "edgecast"]),
    ("Distil Networks", ["x-distil-cs", "distil"]),
    ("AzureFrontDoor/WAF", ["x-azure-ref", "x-msedge-ref"]),
]

ATTACK_PAYLOADS = [
    ("xss", "?q=<script>alert(1)</script>"),
    ("sqli", "?id=1'%20OR%20'1'='1"),
    ("lfi", "?file=../../../../etc/passwd"),
    ("cmd", "?cmd=;cat%20/etc/passwd"),
]


class WafDetect(BaseModule):
    name = "web/waf_detect"
    description = "Detect Web Application Firewall / CDN (40+ signatures + behavioral probe)"
    category = "web"
    target_type = "domain/url"
    intrusive = True

    def _register_options(self):
        self.add_option("TARGET", "", True, "Target URL or domain")
        self.add_option("AGGRESSIVE_PROBE", "false", False,
                        "Send attack payloads to probe WAF response (opt-in; may trigger IP ban)")

    def _fingerprint(self, headers_text, body, cookies_text):
        haystack = (headers_text + " " + cookies_text + " " + body[:5000]).lower()
        found = []
        for vendor, sigs in WAF_SIGNATURES:
            for sig in sigs:
                if sig in haystack:
                    found.append((vendor, sig))
                    break
        return found

    def _collect(self, resp):
        headers_text = "\n".join(f"{k}: {v}" for k, v in resp.headers.items())
        cookies_text = "; ".join(f"{c.name}={c.value}" for c in resp.cookies)
        return headers_text, resp.text or "", cookies_text

    def run(self):
        if not self.validate():
            return False

        url = normalize_url(self.get_option("TARGET"))
        aggressive_probe = self.get_option("AGGRESSIVE_PROBE").lower() == "true"

        print(f"\n{Colors.BOLD}{Colors.CYAN}{'='*58}")
        print(f"  WAF / CDN Detection: {url}")
        print(f"{'='*58}{Colors.RESET}\n")

        detected = {}

        # Baseline request
        print_status("Sending baseline request...", "info")
        try:
            # verify=False intentional: WAF/CDN probing must still work on broken-TLS targets
            resp = http.get(url, verify=False, allow_redirects=True)
            baseline_status = resp.status_code
            h, b, c = self._collect(resp)
            for vendor, sig in self._fingerprint(h, b, c):
                detected.setdefault(vendor, []).append(f"baseline:{sig}")
                print_status(f"Signature match: {vendor} ({sig})", "success")
        except Exception as e:
            print_status(f"Baseline request failed: {e}", "error")
            return False

        # Behavioral probing — opt-in and skipped when passive detection already succeeded.
        probe_results = []
        payload_probe_skipped = None
        if len(detected) > 0:
            payload_probe_skipped = "WAF already detected via passive methods"
            print_status(f"Skipping payload probe: {payload_probe_skipped}", "info")
        elif not aggressive_probe:
            payload_probe_skipped = "AGGRESSIVE_PROBE option is false"
            print_status(f"Skipping payload probe: {payload_probe_skipped}", "info")
        else:
            print_status("Sending attack payloads to trigger WAF...", "info")
            for name, payload in ATTACK_PAYLOADS:
                try:
                    presp = http.get(url + payload, verify=False, allow_redirects=False)
                    h, b, c = self._collect(presp)
                    blocked = presp.status_code in (403, 406, 419, 429, 501, 503)
                    probe_results.append({
                        "payload": name,
                        "status_code": presp.status_code,
                        "blocked": blocked,
                    })
                    if blocked:
                        print_status(f"  {name}: blocked (HTTP {presp.status_code})", "warning")
                    for vendor, sig in self._fingerprint(h, b, c):
                        detected.setdefault(vendor, []).append(f"{name}:{sig}")
                except Exception:
                    probe_results.append({"payload": name, "error": True})

        self.results = {
            "target": url,
            "baseline_status": baseline_status,
            "waf_detected": bool(detected),
            "vendors": list(detected.keys()),
            "evidence": detected,
            "probe_results": probe_results,
            "payload_probe_skipped": payload_probe_skipped,
        }

        print(f"\n{Colors.BOLD}{Colors.GREEN if not detected else Colors.YELLOW}{'='*58}")
        if detected:
            print(f"  WAF/CDN DETECTED: {', '.join(detected.keys())}")
        else:
            blocked_any = any(p.get("blocked") for p in probe_results)
            if blocked_any:
                print(f"  Likely WAF present (payloads blocked) - vendor unknown")
                self.results["waf_detected"] = True
            else:
                print(f"  No WAF/CDN detected")
        print(f"{'='*58}{Colors.RESET}\n")

        return True
