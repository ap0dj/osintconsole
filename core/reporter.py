    def generate_html_report(self, target, all_results):
        """Produce a styled, self-contained HTML report."""
        target_dir = self._target_dir(target)
        ts = timestamp()
        html_path = os.path.join(target_dir, f"report_{ts}.html")
        body = []
        for module_name, data in all_results.items():
            body.append(f'<section><h2>{self._esc(module_name)}</h2>')
            body.append(self._html_node(data))
            body.append('</section>')
        html = _HTML_TEMPLATE.format(
            target=self._esc(target),
            date=datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            modules=len(all_results),
            body="\n".join(body),
        )
        with open(html_path, "w", encoding="utf-8") as f:
            f.write(html)
        return html_path

    @staticmethod
    def _esc(text):
        # Single quotes are escaped too: entity values come from scraped pages,
        # so an attribute written with single quotes must stay safe as well.
        return (str(text).replace("&", "&amp;").replace("<", "&lt;")
                .replace(">", "&gt;").replace('"', "&quot;")
                .replace("'", "&#39;"))

    def _html_node(self, data):
        if isinstance(data, dict):
            if not data:
                return '<span class="empty">(empty)</span>'
            rows = []
            for key, value in data.items():
                rows.append(
                    f'<tr><th>{self._esc(key)}</th><td>{self._html_node(value)}</td></tr>')
            return f'<table>{"".join(rows)}</table>'
        elif isinstance(data, list):
            if not data:
                return '<span class="empty">(none)</span>'
            items = [f'<li>{self._html_node(item)}</li>' for item in data]
            return f'<ul>{"".join(items)}</ul>'
        else:
            text = self._esc(data)
            if isinstance(data, str) and data.startswith("http"):
                return f'<a href="{text}" target="_blank" rel="noopener">{text}</a>'
            return f'<span class="val">{text}</span>'

