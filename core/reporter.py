def _safe_json_for_html(obj):
    """Escape JSON data for safe interpolation inside <script> tags.

    Angle brackets become \\u003c / \\u003e, which JSON decodes back to the same
    characters. Escaping only "</" would be enough to stop the script tag being
    closed, but leaving a bare "<img ...>" in the payload means the page's safety
    depends on how every consumer of the data handles it. None survive here.
    """
    return (json.dumps(obj, ensure_ascii=False, default=str)
            .replace("<", "\\u003c").replace(">", "\\u003e")
            .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


class Reporter:
    def __init__(self, output_dir="results"):
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)

    def _target_dir(self, target):
        safe = "".join(c if c.isalnum() or c in ".-_" else "_" for c in target)
        # Strip leading dots and reject empty after sanitization
        safe = safe.lstrip(".") or "_"
        # Final absolute-path check: result must stay inside output_dir
        target_dir = os.path.abspath(os.path.join(self.output_dir, safe))
        output_abs = os.path.abspath(self.output_dir)
        if not target_dir.startswith(output_abs + os.sep) and target_dir != output_abs:
            target_dir = os.path.join(output_abs, "_invalid")
        os.makedirs(target_dir, exist_ok=True)
        return target_dir

    def save_module_result(self, target, module_name, data):
        target_dir = self._target_dir(target)
        ts = timestamp()
        safe_module = module_name.replace("/", "_").replace("\\", "_")
        json_path = os.path.join(target_dir, f"{safe_module}_{ts}.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False, default=str)
        txt_path = os.path.join(target_dir, f"{safe_module}_{ts}.txt")
        with open(txt_path, "w", encoding="utf-8") as f:
            f.write(f"{'='*60}\n")
            f.write(f"  OsintConsole Report\n")
            f.write(f"  Module: {module_name}\n")
            f.write(f"  Target: {target}\n")
            f.write(f"  Date:   {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
            f.write(f"{'='*60}\n\n")
            self._write_dict(f, data)
        return json_path, txt_path

    def _write_dict(self, f, data, indent=0):
        prefix = "  " * indent
        if isinstance(data, dict):
            for key, value in data.items():
                if isinstance(value, (dict, list)):
                    f.write(f"{prefix}[{key}]\n")
                    self._write_dict(f, value, indent + 1)
                else:
                    f.write(f"{prefix}{key}: {value}\n")
        elif isinstance(data, list):
            for i, item in enumerate(data):
                if isinstance(item, (dict, list)):
                    f.write(f"{prefix}--- Entry {i+1} ---\n")
                    self._write_dict(f, item, indent + 1)
                else:
                    f.write(f"{prefix}- {item}\n")
        else:
            f.write(f"{prefix}{data}\n")

    def generate_full_report(self, target, all_results):
        target_dir = self._target_dir(target)
        ts = timestamp()
        md_path = os.path.join(target_dir, f"full_report_{ts}.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(f"# OsintConsole - Full Reconnaissance Report\n\n")
