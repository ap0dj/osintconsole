    # Longest entity list rendered per type before the rest is summarised.
    MAX_ROWS_PER_TYPE = 150

    # Confidence values that have a matching CSS rule; anything else is styled
    # as the weakest tier rather than emitting an arbitrary class name.
    BADGE_TIERS = ("strong", "corroborated", "single-source")

    def generate_correlation_report(self, target, correlation, scan_meta=None):
        """Interactive report built from a core.correlate.correlate() result."""
        target_dir = self._target_dir(target)
        path = os.path.join(target_dir, f"recon_{timestamp()}.html")

        meta = scan_meta or {}
        entities = correlation.get("entities") or {}
        totals = correlation.get("totals") or {}
        corroborated = correlation.get("corroborated") or []
        pivots = correlation.get("pivot_suggestions") or []
        graph = correlation.get("graph") or {"nodes": [], "edges": []}

        subtitle = " &nbsp;|&nbsp; ".join(filter(None, [
            f"type <b>{self._esc(correlation.get('target_type') or 'unknown')}</b>",
            f"<b>{meta['modules_run']}</b> modules ran" if meta.get("modules_run")
            is not None else "",
            f"<b>{meta['modules_failed']}</b> failed" if meta.get("modules_failed")
            else "",
            f"<b>{meta['duration_seconds']}s</b>" if meta.get("duration_seconds")
            else "",
        ]))

        stats = [
            ("", correlation.get("total_entities", 0), "entities"),
            ("ok", len(corroborated), "corroborated"),
            ("warn", len(pivots), "pivot leads"),
            ("", len(correlation.get("modules_contributing") or []), "modules w/ hits"),
        ]
        if meta.get("modules_failed"):
            stats.append(("bad", meta["modules_failed"], "failed"))
        stats_html = "".join(
            f'<div class="stat {cls}"><span class="n">{value}</span>'
            f'<span class="l">{self._esc(label)}</span></div>'
            for cls, value, label in stats
        )

        chips_html = "".join(
            f'<button class="chip" data-type="{self._esc(kind)}" aria-pressed="true">'
            f'<span class="dot" style="background:{self._colour(kind)}"></span>'
            f'{self._esc(kind)} <b>{count}</b></button>'
            for kind, count in sorted(totals.items(), key=lambda kv: -kv[1])
        )

        body = []

        body.append('<section><h2>Confirmed by two or more modules</h2><div class="card">')
        body.append("".join(self._entity_row(e, e.get("type"))
                            for e in corroborated[:60])
                    or '<div class="empty">Nothing was reported by more than one '
                       'module &mdash; treat every finding below as single-source.</div>')
        body.append("</div></section>")

        if pivots:
            body.append('<section><h2>Worth pivoting on</h2><div class="card">')
            for pivot in pivots:
                cmd = self._esc(pivot["command"])
                body.append(
                    f'<div class="cmd"><span class="dot" '
                    f'style="background:{self._colour(pivot["type"])}"></span>'
                    f'<code>{cmd}</code>'
                    f'<button class="copy" data-copy="{cmd}">copy</button></div>'
                )
            body.append("</div></section>")

        body.append("<section><h2>All findings by type</h2>")
        for kind, group in sorted(entities.items(), key=lambda kv: -len(kv[1])):
            shown = group[:self.MAX_ROWS_PER_TYPE]
            rows = "".join(self._entity_row(e, kind) for e in shown)
            if len(group) > len(shown):
                rows += (f'<div class="more">&hellip; and {len(group) - len(shown)} '
                         f'more (see the JSON report)</div>')
            body.append(
                f'<details data-type="{self._esc(kind)}">'
                f'<summary><span class="dot" style="background:{self._colour(kind)}">'
                f'</span>{self._esc(kind)} <b style="color:var(--muted);'
                f'font-weight:600">{len(group)}</b></summary>{rows}</details>'
            )
        body.append("</section>")

        html = (_CORRELATION_TEMPLATE
                .replace("__TARGET__", self._esc(target))
                .replace("__SUBTITLE__", subtitle)
                .replace("__DATE__", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
                .replace("__STATS__", stats_html)
                .replace("__CHIPS__", chips_html)
                .replace("__BODY__", "".join(body))
                .replace("__GRAPH_JSON__", _safe_json_for_html(
                    self._vis_payload(graph)))
                .replace("__COLORS_JSON__", _safe_json_for_html(self.GROUP_COLORS)))
        with open(path, "w", encoding="utf-8") as f:
            f.write(html)
        return path

    def _colour(self, group):
        return self.GROUP_COLORS.get(group, self.GROUP_COLORS["other"])

    def _entity_row(self, entity, kind):
        value = str(entity.get("value", ""))
        kind = kind or "other"
        confidence = entity.get("confidence", "single-source")
        tier = confidence if confidence in self.BADGE_TIERS else "single-source"
        modules = entity.get("modules") or []
        safe = self._esc(value)
        display = (f'<a href="{safe}" target="_blank" rel="noopener">{safe}</a>'
                   if value.startswith(("http://", "https://")) else safe)
        return (
            f'<div class="ent" data-type="{self._esc(kind)}" '
            f'data-val="{self._esc(value.lower())}">'
            f'<span class="dot" style="background:{self._colour(kind)}"></span>'
            f'<span class="v mono">{display}'
            f'<span class="src">{self._esc(", ".join(modules)) or "&mdash;"}</span>'
            f'</span>'
            f'<span class="badge {tier}">{self._esc(confidence)}</span>'
            f'<button class="copy" data-copy="{safe}">copy</button>'
            f'</div>'
        )

    def _vis_payload(self, graph):
        nodes = []
        for node in graph.get("nodes") or []:
            group = node.get("group", "other")
            nodes.append({
                "id": node["id"],
                "label": str(node.get("label", node["id"]))[:34],
                "group": group,
                "title": node.get("title", ""),
                "value": node.get("value", 1),
                "color": self._colour(group),
            })
        edges = [{"from": e["from"], "to": e["to"], "label": e.get("label", "")}
                 for e in (graph.get("edges") or [])]
        return {"nodes": nodes, "edges": edges}

    def generate_graph_html(self, target, nodes, edges, sections=None):
        """Interactive relationship graph (vis-network) + optional detail sections.

        nodes: list of {id, label?, group?, title?, value?}
        edges: list of {from, to, label?}
        sections: list of (heading, html_body)
        """
        target_dir = self._target_dir(target)
        ts = timestamp()
        path = os.path.join(target_dir, f"graph_{ts}.html")

        vis_nodes = []
        for n in nodes:
            group = n.get("group", "other")
            vis_nodes.append({
                "id": n["id"],
                "label": n.get("label", str(n["id"]))[:40],
                "group": group,
                "title": n.get("title", ""),
                "value": n.get("value", 1),
                "color": self.GROUP_COLORS.get(group, self.GROUP_COLORS["other"]),
            })
        vis_edges = [{"from": e["from"], "to": e["to"],
                      "label": e.get("label", ""), "arrows": "to"} for e in edges]

        legend = "".join(
            f'<span class="lg"><i style="background:{c}"></i>{g}</span>'
            for g, c in self.GROUP_COLORS.items()
            if any(n.get("group") == g for n in nodes))

        section_html = ""
        for heading, body in (sections or []):
            section_html += f'<section><h2>{self._esc(heading)}</h2>{body}</section>'

        html = (_GRAPH_TEMPLATE
                .replace("__TARGET__", self._esc(target))
                .replace("__DATE__", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
                .replace("__NODE_COUNT__", str(len(vis_nodes)))
                .replace("__EDGE_COUNT__", str(len(vis_edges)))
                .replace("__LEGEND__", legend)
                .replace("__SECTIONS__", section_html)
                .replace("__NODES_JSON__", _safe_json_for_html(vis_nodes))
                .replace("__EDGES_JSON__", _safe_json_for_html(vis_edges)))
        with open(path, "w", encoding="utf-8") as f:
            f.write(html)
        return path

    def _write_md_section(self, f, data, depth=0):
        if isinstance(data, dict):
            for key, value in data.items():
                if isinstance(value, (dict, list)):
                    f.write(f"{'  '*depth}**{key}:**\n\n")
                    self._write_md_section(f, value, depth + 1)
                else:
                    f.write(f"{'  '*depth}- **{key}:** `{value}`\n")
        elif isinstance(data, list):
            for item in data:
                if isinstance(item, dict):
                    for k, v in item.items():
                        f.write(f"{'  '*depth}- **{k}:** `{v}`\n")
                    f.write(f"\n")
                else:
                    f.write(f"{'  '*depth}- `{item}`\n")
        else:
            f.write(f"{'  '*depth}`{data}`\n")
